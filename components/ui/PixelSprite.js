function parseArt(art) {
  const rows = art.trim().split("\n");
  const width = Math.max(...rows.map((row) => row.length));
  const cells = [];

  rows.forEach((row, y) => {
    for (let x = 0; x < width; x += 1) {
      const colorKey = row[x];

      if (!colorKey || colorKey === "." || colorKey === " ") continue;
      cells.push({ colorKey, x, y });
    }
  });

  return { cells, height: rows.length, width };
}

export default function PixelSprite({ name, scale = 3, className = "", style }) {
  const sprite = SPRITES[name] ?? SPRITES.coin;
  const { cells, height, width } = parseArt(sprite.art);

  return (
    <svg
      aria-hidden="true"
      className={`block [image-rendering:pixelated] ${className}`}
      height={height * scale}
      style={style}
      viewBox={`0 0 ${width} ${height}`}
      width={width * scale}
      preserveAspectRatio="xMidYMid meet"
      shapeRendering="crispEdges"
    >
      {cells.map((cell, index) => (
        <rect
          key={`${cell.x}-${cell.y}-${index}`}
          fill={sprite.palette[cell.colorKey] ?? "#ff00ff"}
          height="1"
          width="1"
          x={cell.x}
          y={cell.y}
        />
      ))}
    </svg>
  );
}

export function CoinIcon({ size = 18 }) {
  return <PixelSprite name="coin" scale={size / 8} />;
}
